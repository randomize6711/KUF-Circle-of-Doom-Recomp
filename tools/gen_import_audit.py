#!/usr/bin/env python3
"""Generate src/runtime/import_audit_table.inc from config/<ver>/imports.txt.

Usage: gen_import_audit.py config/v1/imports.txt src/runtime/import_audit_table.inc
Each line becomes KUF_IMPORT(name, index), expanded by src/runtime/import_audit.cpp.
"""
import sys

src, dst = sys.argv[1:3]
names = []
for line in open(src):
    line = line.strip()
    if line and not line.startswith("#"):
        names.append(line.split()[0])
with open(dst, "w") as f:
    f.write("// Generated by tools/gen_import_audit.py from %s -- do not edit.\n" % src)
    for i, n in enumerate(names):
        f.write("KUF_IMPORT(%s, %d)\n" % (n, i))
    f.write("#define KUF_IMPORT_COUNT %d\n" % len(names))
print(len(names), "imports")
